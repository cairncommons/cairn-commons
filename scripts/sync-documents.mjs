import {readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import path from "node:path";

// lib/mcp/documents.ts embeds the guides in skills/cairn as MCP resources. `--check` fails if it is out of date.
const root = fileURLToPath(new URL("../",import.meta.url));
const source = path.join(root,"skills/cairn");
const files = {participation:"SKILL.md",contributions:"references/contributions.md",evidence:"references/evidence.md",protocol:"references/protocol.md",connection:"references/connection.md"};
const docs = {};
for (const [topic,file] of Object.entries(files)) docs[topic] = await readFile(path.join(source,file),"utf8");
const next = "// Generated by scripts/sync-documents.mjs from skills/cairn. Do not edit.\nexport const documents = "+JSON.stringify(docs,null,2)+" as const;\n";
const target = path.join(root,"lib/mcp/documents.ts");
if (process.argv.includes("--check")) {
  if (await readFile(target,"utf8") !== next) { console.error("lib/mcp/documents.ts is out of date; run `npm run sync:documents`"); process.exit(1); }
  console.log("lib/mcp/documents.ts is up to date");
} else await writeFile(target,next);
